try:
    from scripts.complete_residual_map import COMPLETE_RESIDUALS
    TRANSLATIONS.update(COMPLETE_RESIDUALS)
except Exception:
    pass

def auto_translate(text):
    if text in TRANSLATIONS:
        return TRANSLATIONS[text]

    out = text
    # Replace known phrases from LEXICON
    for zh, en in LEXICON:
        if zh in out:
            out = out.replace(zh, en)

    # Replace known residuals
    for zh, en in TRANSLATIONS.items():
        if zh in out:
            out = out.replace(zh, en)

    # Clean up any leftover Chinese numbers or characters
    out = re.sub(r'(\d+)\s*秒', r'\1s', out)
    out = re.sub(r'(\d+)\s*天', r'\1 days', out)
    out = re.sub(r'(\d+)\s*字', r'\1 words', out)
    out = re.sub(r'第\s*(\d+)\s*页', r'Page \1', out)

    return out

